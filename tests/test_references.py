ADR = """# ADR-009: Example

## Decision

Untagged opening.

<!-- rule:skip-list -->
The skip list is `.git` and `build`.

It applies to every language.
<!-- /rule:skip-list -->

Untagged closing.
"""

SKILL = "Skips the folders on the [skip list](references/skip-list.md).\n"

EXPECTED_REFERENCE = """# Skip list

Generated by `qg-references` from ADR-009, section "Decision", in the quality-gates repo. To change this rule, edit that section and rerun `qg-references`.

The skip list is `.git` and `build`.

It applies to every language.
"""


class Repo:
    def __init__(self):
        self.root = Path(tempfile.mkdtemp())
        self.adr_dir = self.root / "docs" / "adr"
        self.skills = self.root / "skills"

    def write(self, relative, text):
        path = self.root / relative
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")
        return path

    def read(self, relative):
        return (self.root / relative).read_text(encoding="utf-8")

    def generate(self):
        return references.generate(self.adr_dir, self.skills).problems

    def check(self):
        return references.check(self.adr_dir, self.skills)

    def main(self, *extra):
        out = io.StringIO()
        code = None
        with contextlib.redirect_stdout(out), contextlib.redirect_stderr(out):
            try:
                references.main(["--adr-dir", str(self.adr_dir), "--skills", str(self.skills), *extra])
            except SystemExit as stop:
                code = stop.code
        return code, out.getvalue()


class Generator(unittest.TestCase):
    def setUp(self):
        self.repo = Repo()
        self.repo.write("docs/adr/ADR-009-example.md", ADR)
        self.repo.write("skills/crap/SKILL.md", SKILL)

    def test_a_skill_that_links_a_rule_gets_the_tagged_adr_section_as_its_reference_file(self):
        self.assertEqual(self.repo.generate(), [])
        self.assertEqual(self.repo.read("skills/crap/references/skip-list.md"), EXPECTED_REFERENCE)

    def test_running_the_generator_twice_changes_no_reference_file(self):
        self.repo.generate()
        first = self.repo.read("skills/crap/references/skip-list.md")
        self.assertEqual(self.repo.generate(), [])
        self.assertEqual(self.repo.read("skills/crap/references/skip-list.md"), first)
        self.assertEqual(self.repo.check(), [])

    def test_editing_a_tagged_adr_sentence_without_regenerating_fails_the_check(self):
        self.repo.generate()
        self.repo.write("docs/adr/ADR-009-example.md", ADR.replace("`.git` and `build`", "`.git`, `build` and `dist`"))
        self.assertEqual(self.repo.check(), ["crap/references/skip-list.md: differs from rule:skip-list in ADR-009"])

    def test_a_hand_edited_reference_file_fails_the_check_and_the_generator_restores_it(self):
        self.repo.generate()
        self.repo.write("skills/crap/references/skip-list.md", "edited by hand\n")
        self.assertEqual(self.repo.check(), ["crap/references/skip-list.md: differs from rule:skip-list in ADR-009"])
        self.repo.generate()
        self.assertEqual(self.repo.read("skills/crap/references/skip-list.md"), EXPECTED_REFERENCE)

    def test_a_reference_file_that_was_never_generated_fails_the_check(self):
        self.assertEqual(self.repo.check(), ["crap/references/skip-list.md: missing; run qg-references"])

    def test_untagged_adr_text_never_reaches_a_reference_file(self):
        self.repo.generate()
        text = self.repo.read("skills/crap/references/skip-list.md")
        self.assertNotIn("Untagged", text)
        self.assertNotIn("rule:", text)

    def test_the_reference_file_names_the_nested_section_its_rule_sits_in(self):
        self.repo.write("docs/adr/ADR-009-example.md", ADR.replace("Untagged opening.", "### Scope"))
        self.repo.generate()
        self.assertIn('section "Decision › Scope"', self.repo.read("skills/crap/references/skip-list.md"))


class BrokenTagsAndLinks(unittest.TestCase):
    def setUp(self):
        self.repo = Repo()
        self.repo.write("skills/crap/SKILL.md", SKILL)

    def test_a_tag_with_no_closing_tag_fails_the_check_and_writes_nothing(self):
        self.repo.write("docs/adr/ADR-009-example.md", ADR.replace("<!-- /rule:skip-list -->\n", ""))
        problems = self.repo.check()
        self.assertIn("ADR-009-example.md:7: rule:skip-list has no closing tag", problems)
        self.assertEqual(self.repo.generate(), problems)
        self.assertFalse((self.repo.skills / "crap" / "references").exists())

    def test_a_closing_tag_with_no_opening_tag_fails_the_check(self):
        self.repo.write("docs/adr/ADR-009-example.md", ADR.replace("<!-- rule:skip-list -->\n", ""))
        self.assertIn("ADR-009-example.md:10: /rule:skip-list closes a tag that is not open", self.repo.check())

    def test_a_tag_name_used_twice_fails_the_check(self):
        self.repo.write("docs/adr/ADR-009-example.md", ADR)
        self.repo.write("docs/adr/ADR-010-later.md", "## Addendum\n\n<!-- rule:skip-list -->\nNew.\n<!-- /rule:skip-list -->\n")
        self.assertIn("rule:skip-list is tagged twice, at ADR-009-example.md:7 and ADR-010-later.md:3", self.repo.check())

    def test_a_tag_name_used_twice_in_one_adr_names_both_lines(self):
        self.repo.write("docs/adr/ADR-009-example.md", ADR + "\n<!-- rule:skip-list -->\nAgain.\n<!-- /rule:skip-list -->\n")
        self.assertIn("rule:skip-list is tagged twice, at ADR-009-example.md:7 and ADR-009-example.md:15", self.repo.check())

    def test_a_tag_opened_twice_in_one_adr_fails_the_check(self):
        self.repo.write("docs/adr/ADR-009-example.md", ADR.replace("It applies", "<!-- rule:skip-list -->\nIt applies"))
        self.assertIn("ADR-009-example.md:10: rule:skip-list is opened again before it is closed", self.repo.check())

    def test_a_tag_shown_inside_a_code_fence_is_an_example_not_a_tag(self):
        self.repo.write("docs/adr/ADR-009-example.md", ADR)
        self.repo.write("docs/adr/ADR-010-tags.md", "## Decision\n\n```markdown\n<!-- rule:skip-list -->\n```\n")
        self.repo.generate()
        self.assertEqual(self.repo.check(), [])

    def test_a_tag_shown_inside_a_tilde_or_four_backtick_fence_is_an_example_not_a_tag(self):
        self.repo.write("docs/adr/ADR-009-example.md", ADR)
        example = "```\n<!-- rule:skip-list -->\n```\n"
        self.repo.write("docs/adr/ADR-010-tags.md", f"## Decision\n\n~~~\n{example}~~~\n\n````markdown\n{example}````\n")
        self.repo.generate()
        self.assertEqual(self.repo.check(), [])

    def test_a_link_the_generator_cannot_read_fails_the_check_and_nothing_is_removed(self):
        self.repo.write("docs/adr/ADR-009-example.md", ADR)
        self.repo.generate()
        self.repo.write("skills/crap/SKILL.md", "See [the list](references/Skip-List.md).\n")
        self.assertEqual(self.repo.generate(), [
            "crap/SKILL.md: cannot read the link references/Skip-List.md; write it as references/<name>.md",
        ])
        self.assertTrue((self.repo.skills / "crap" / "references" / "skip-list.md").is_file())

    def test_a_skill_link_to_a_rule_no_adr_tags_fails_the_check(self):
        self.repo.write("docs/adr/ADR-009-example.md", ADR)
        self.repo.write("skills/crap/SKILL.md", SKILL + "See [keys](references/baseline-keys.md).\n")
        self.assertEqual(self.repo.check(), [
            "crap/SKILL.md: links references/baseline-keys.md, but no ADR tags rule:baseline-keys",
            "crap/references/skip-list.md: missing; run qg-references",
        ])

    def test_a_skill_link_that_misses_its_skills_references_folder_fails_the_check(self):
        self.repo.write("docs/adr/ADR-009-example.md", ADR)
        self.repo.write("skills/standards/principles/ask.md", "See [the list](references/skip-list.md).\n")
        self.assertIn("standards/principles/ask.md: the link to skip-list.md does not reach its skill's references folder",
                      self.repo.check())


