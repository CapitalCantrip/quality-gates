class AmendmentLinks(unittest.TestCase):
    def setUp(self):
        self.repo = Repo()
        self.repo.skills.mkdir(parents=True)

    def check(self, text):
        self.repo.write("docs/adr/ADR-009-example.md", text)
        return self.repo.check()

    def test_an_amendment_and_the_text_it_amends_that_link_both_ways_pass_the_check(self):
        self.assertEqual(self.check(AMENDED), [])

    def test_an_addendum_with_no_amends_line_fails_the_check(self):
        text = AMENDED.replace("Amends: [Decision](#decision)\n", "").replace("Amended by: [Addendum 2026-10-12: the `(set)` rule (v0.9.1)](#addendum-2026-10-12-the-set-rule-v091)\n", "")
        self.assertEqual(self.check(text), [
            'ADR-009-example.md:12: "Addendum 2026-10-12: the `(set)` rule (v0.9.1)" amends nothing; add an Amends: line linking the text it changes',
        ])

    def test_a_restated_current_rule_with_no_amends_line_fails_the_check(self):
        text = AMENDED.replace("Amends: [the second Rejected](#rejected-1)\n", "")
        self.assertIn('ADR-009-example.md:25: "Current rule, restated 2026-10-12: the rule" amends nothing; '
                      'add an Amends: line linking the text it changes', self.check(text))

    def test_text_that_does_not_link_forward_to_its_amendment_fails_the_check(self):
        text = AMENDED.replace("Amended by: [Addendum 2026-10-12: the `(set)` rule (v0.9.1)](#addendum-2026-10-12-the-set-rule-v091)\n", "")
        self.assertEqual(self.check(text), [
            'ADR-009-example.md:12: "Addendum 2026-10-12: the `(set)` rule (v0.9.1)" amends "Decision", '
            'but "Decision" has no Amended by: link back to it',
        ])

    def test_a_forward_link_the_amendment_does_not_return_fails_the_check(self):
        text = AMENDED.replace("Amends: [Decision](#decision)\n", "Amends: [Rejected](#rejected)\n")
        problems = self.check(text)
        self.assertIn('ADR-009-example.md:3: "Decision" is amended by "Addendum 2026-10-12: the `(set)` rule (v0.9.1)", '
                      'but "Addendum 2026-10-12: the `(set)` rule (v0.9.1)" has no Amends: link to it', problems)

    def test_a_link_to_an_anchor_no_heading_has_fails_the_check(self):
        text = AMENDED.replace("(#decision)", "(#the-decision)")
        self.assertIn("ADR-009-example.md:15: links #the-decision, which no heading in this ADR has", self.check(text))

    def test_a_link_in_a_heading_counts_by_its_text_in_the_heading_anchor(self):
        text = AMENDED.replace("## Decision\n", "## Decision on [lizard](https://github.com/terryyin/lizard)\n")
        self.assertEqual(self.check(text.replace("(#decision)", "(#decision-on-lizard)")), [])

    def test_a_repeated_heading_gets_its_anchor_numbered_from_one(self):
        text = AMENDED.replace("(#rejected-1)", "(#rejected)")
        self.assertIn('ADR-009-example.md:19: "Rejected" is amended by "Current rule, restated 2026-10-12: the rule", '
                      'but "Current rule, restated 2026-10-12: the rule" has no Amends: link to it', self.check(text))

    def test_an_amends_line_inside_a_code_fence_is_an_example(self):
        self.assertEqual(self.check(AMENDED + "\n```markdown\nAmends: [Nowhere](#nowhere)\n```\n"), [])


class ReferenceFolders(unittest.TestCase):
    def setUp(self):
        self.repo = Repo()
        self.repo.write("docs/adr/ADR-009-example.md", ADR)

    def test_a_file_in_a_subfolder_gets_its_reference_in_its_skills_own_references_folder(self):
        self.repo.write("skills/standards/principles/ask.md", "See [the list](../references/skip-list.md).\n")
        self.assertEqual(self.repo.generate(), [])
        self.assertEqual(self.repo.read("skills/standards/references/skip-list.md"), EXPECTED_REFERENCE)

    def test_a_dot_slash_link_or_a_link_with_an_anchor_gets_its_reference_file(self):
        self.repo.write("skills/crap/SKILL.md", "See [the list](./references/skip-list.md).\n")
        self.repo.write("skills/cc-python/SKILL.md", "See [the list](references/skip-list.md#skip-list).\n")
        self.assertEqual(self.repo.generate(), [])
        self.assertEqual(self.repo.read("skills/crap/references/skip-list.md"), EXPECTED_REFERENCE)
        self.assertEqual(self.repo.read("skills/cc-python/references/skip-list.md"), EXPECTED_REFERENCE)

    def test_skills_named_by_a_path_that_climbs_several_folders_still_resolve(self):
        self.repo.write("skills/standards/principles/ask.md", "See [the list](../references/skip-list.md).\n")
        climbing = os.path.relpath(self.repo.skills, Path.cwd())
        self.assertTrue(climbing.startswith(os.path.join("..", "..")))
        adr_dir = os.path.relpath(self.repo.adr_dir, Path.cwd())
        self.assertEqual(references.generate(adr_dir, climbing).problems, [])
        self.assertEqual(references.check(adr_dir, climbing), [])

    def test_every_skill_that_links_a_rule_gets_its_own_copy(self):
        self.repo.write("skills/crap/SKILL.md", SKILL)
        self.repo.write("skills/cc-python/SKILL.md", SKILL)
        self.repo.generate()
        self.assertEqual(self.repo.read("skills/cc-python/references/skip-list.md"), EXPECTED_REFERENCE)
        self.assertEqual(self.repo.read("skills/crap/references/skip-list.md"), EXPECTED_REFERENCE)

    def test_a_reference_file_no_skill_links_fails_the_check_and_the_generator_removes_it(self):
        self.repo.write("skills/crap/SKILL.md", SKILL)
        self.repo.generate()
        self.repo.write("skills/crap/SKILL.md", "No links any more.\n")
        self.assertEqual(self.repo.check(), ["crap/references/skip-list.md: not generated; run qg-references"])
        self.assertEqual(self.repo.generate(), [])
        self.assertFalse((self.repo.skills / "crap" / "references").exists())
        self.assertEqual(self.repo.check(), [])


class Command(unittest.TestCase):
    def setUp(self):
        self.repo = Repo()
        self.repo.write("docs/adr/ADR-009-example.md", ADR)
        self.repo.write("skills/crap/SKILL.md", SKILL)

    def test_qg_references_writes_the_files_and_says_how_many(self):
        code, out = self.repo.main()
        self.assertEqual(code, 0)
        self.assertIn("Wrote 1 reference file(s)", out)
        self.assertTrue((self.repo.skills / "crap" / "references" / "skip-list.md").is_file())

    def test_qg_references_check_exits_1_and_names_each_problem(self):
        code, out = self.repo.main("--check")
        self.assertEqual(code, 1)
        self.assertIn("crap/references/skip-list.md: missing; run qg-references", out)

    def test_qg_references_check_exits_0_when_every_reference_file_matches(self):
        self.repo.main()
        code, out = self.repo.main("--check")
        self.assertEqual(code, 0)
        self.assertIn("match", out)

    def test_the_module_runs_as_a_script(self):
        argv = sys.argv
        sys.argv = ["qg-references", "--adr-dir", str(self.repo.adr_dir), "--skills", str(self.repo.skills)]
        try:
            with contextlib.redirect_stdout(io.StringIO()), self.assertRaises(SystemExit) as stop:
                runpy.run_module("quality_gates.references", run_name="__main__")
        finally:
            sys.argv = argv
        self.assertEqual(stop.exception.code, 0)
        self.assertTrue((self.repo.skills / "crap" / "references" / "skip-list.md").is_file())

    def test_qg_references_exits_1_without_writing_when_a_tag_is_broken(self):
        self.repo.write("docs/adr/ADR-009-example.md", ADR.replace("<!-- /rule:skip-list -->\n", ""))
        code, out = self.repo.main()
        self.assertEqual(code, 1)
        self.assertIn("rule:skip-list has no closing tag", out)


