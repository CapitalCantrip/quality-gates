def shell_lines(source):
    return list(cd.LANGUAGES['shell'].checker(source, ()))


class ShellCountingTest(unittest.TestCase):

    def test_a_hash_comment_counts_on_its_own_line_and_after_code(self):
        self.assertEqual(shell_lines('# why\necho hi # also why\nls;# and\n'), [1, 2, 3])

    def test_a_hash_in_quotes_or_inside_a_word_is_not_a_comment(self):
        source = ("echo 'a # b' \"c # d \\\" # e\" $'f\\' # g'\n"
                  "echo it\\'s # one 'x'\nurl=http://x/#top\n")
        self.assertEqual(shell_lines(source), [2])

    def test_the_argument_count_and_a_length_expansion_are_not_comments(self):
        self.assertEqual(shell_lines('echo $# ${#x} ${#arr[@]} ${x#pre} $((16#ff))\n'), [])

    def test_a_heredoc_body_is_not_a_comment_and_what_follows_it_is_read_again(self):
        source = ("cat <<EOF\n# not a comment\nEOF\n# counted\ncat <<-'END'\n\t# no\n\tEND\n"
                  "cat <<< \"# no\"\nx=$((1<<2)) # counted\n")
        self.assertEqual(shell_lines(source), [4, 9])

    def test_a_comment_after_a_heredoc_opener_counts_because_the_body_starts_on_the_next_line(self):
        for source in ('cat <<EOF # note\nhi\nEOF\n', 'cat > "$f" <<EOF  # write config\nk=v\nEOF\n',
                       "cat <<-'END' # note\n\t# no\n\tEND\n"):
            with self.subTest(source=source):
                self.assertEqual(shell_lines(source), [1])

    def test_two_heredocs_opened_on_one_line_read_their_bodies_one_after_the_other(self):
        source = 'cmd <<A <<B # note\n# in a\nA\n# in b\nB\n# counted\n'
        self.assertEqual(shell_lines(source), [1, 6])

    def test_a_shift_inside_arithmetic_is_not_a_heredoc(self):
        for source in ('echo $(( x << y )) # note\n# another\ny\n', '(( x << y )) # note\n# another\ny\n',
                       'echo $(( (a << b) + c )) # note\n# another\nb\n'):
            with self.subTest(source=source):
                self.assertEqual(shell_lines(source), [1, 2])

    def test_a_command_substitution_inside_double_quotes_nests_its_own_quotes(self):
        for source, lines in (('x="$(echo "a # b")"\n', []), ('x="$(f "$(g "# c")" "# d")" # e\n', [1]),
                              ('x="$((1 + 2)) # f"\n', []), ('x="$(echo "a # b")\n# g"\n', [])):
            with self.subTest(source=source):
                self.assertEqual(shell_lines(source), lines)

    def test_a_comment_inside_a_command_substitution_inside_double_quotes_counts(self):
        self.assertEqual(shell_lines('x="$(echo hi # why\n)"\n'), [1])

    def test_a_heredoc_whose_delimiter_never_comes_is_read_as_code(self):
        self.assertEqual(shell_lines('cat <<EOF\n# counted\n'), [2])

    def test_the_shebang_on_line_one_is_exempt_and_anywhere_else_counts(self):
        self.assertEqual(shell_lines('#!/usr/bin/env bash\necho hi\n'), [])
        self.assertEqual(shell_lines('echo hi\n#!/bin/sh\n'), [2])

    def test_a_bare_shellcheck_directive_is_exempt_and_one_that_carries_prose_counts(self):
        for pragma in ('# shellcheck disable=SC2034', '# shellcheck disable=SC2034,SC2086', 'x=1 # shellcheck disable=SC2154'):
            with self.subTest(pragma=pragma):
                self.assertEqual(shell_lines(f'{pragma}\necho hi\n'), [])
        self.assertEqual(shell_lines('# shellcheck disable=SC2034 because it is exported\necho hi\n'), [1])


class RatchetTest(unittest.TestCase):

    def judged(self, counts, baseline):
        found = [ratchet.Finding(ratchet.Location(path), n, cd.FINDING_KIND, '') for path, n in counts.items()]
        return ratchet.judge(found, baseline)

    def outcomes(self, counts, baseline):
        return {v.location.key: (v.outcome, v.now, v.allowed) for v in self.judged(counts, baseline).verdicts}

    def test_a_new_file_with_a_comment_is_over(self):
        self.assertEqual(self.outcomes({'new.py': 1}, {}), {'new.py': (ratchet.Outcome.FAILED, 1, None)})

    def test_a_file_at_its_baseline_passes(self):
        self.assertEqual(self.outcomes({'a.py': 2}, {'a.py': 2}), {'a.py': (ratchet.Outcome.PASSED, 2, 2)})

    def test_a_file_below_its_baseline_is_reported_as_paid(self):
        self.assertEqual(self.outcomes({'a.py': 1}, {'a.py': 2}), {'a.py': (ratchet.Outcome.BEHIND, 1, 2)})

    def test_a_baseline_entry_for_a_deleted_file_is_stale(self):
        self.assertEqual(self.outcomes({}, {'gone.py': 4}), {'gone.py': (ratchet.Outcome.BEHIND, None, 4)})

    def test_lowering_never_raises_a_count(self):
        self.assertEqual(ratchet.lowered(self.judged({'a.py': 2}, {'a.py': 3})), {'a.py': 2})

    def test_lowering_drops_files_that_reach_zero(self):
        self.assertEqual(ratchet.lowered(self.judged({'a.py': 0, 'b.py': 1}, {'a.py': 3, 'b.py': 1})), {'b.py': 1})


class RepositoryTest(unittest.TestCase):

    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.root = Path(self.tmp.name)
        subprocess.run(['git', 'init', '-q'], cwd=self.root, check=True)
        self.file = self.root / 'comment-debt.json'

    def tearDown(self):
        self.tmp.cleanup()

    def put(self, name, text):
        (self.root / name).write_text(text)
        subprocess.run(['git', 'add', name], cwd=self.root, check=True)

    def run_gate(self, *argv):
        out = io.StringIO()
        return cd.main(list(argv), root=self.root, baseline=self.file, out=out), out.getvalue()

    def baseline(self):
        return json.loads(self.file.read_text())

    def test_the_check_refuses_to_run_without_a_baseline(self):
        self.assertEqual(self.run_gate()[0], 2)

    def test_the_first_update_records_existing_debt_and_the_check_then_passes(self):
        self.put('a.py', '# one\n# two\nx = 1\n')
        self.assertEqual(self.run_gate('--update')[0], 0)
        self.assertEqual(self.baseline(), {'a.py': 2})
        self.assertEqual(self.run_gate()[0], 0)

    def test_adding_a_comment_fails_the_check_and_names_the_lines(self):
        self.put('a.py', '# one\nx = 1\n')
        self.run_gate('--update')
        self.put('a.py', '# one\nx = 1  # two\n')
        code, out = self.run_gate()
        self.assertEqual(code, 1)
        self.assertIn('a.py: 2 comment lines, baseline allows 1 — lines 1, 2', out)

    def test_update_will_not_record_a_new_comment(self):
        self.put('a.py', 'x = 1\n')
        self.run_gate('--update')
        self.put('a.py', '# new\nx = 1\n')
        self.assertEqual(self.run_gate('--update')[0], 1)
        self.assertEqual(self.baseline(), {})

    def test_paid_debt_fails_the_check_until_the_baseline_is_lowered(self):
        self.put('a.py', '# one\n# two\nx = 1\n')
        self.run_gate('--update')
        self.put('a.py', '# one\nx = 1\n')
        code, out = self.run_gate()
        self.assertEqual(code, 1)
        self.assertIn('PAID a.py', out)
        self.run_gate('--update')
        self.assertEqual(self.baseline(), {'a.py': 1})
        self.assertEqual(self.run_gate()[0], 0)

    def test_the_baseline_defaults_to_comment_debt_json_at_the_repo_root(self):
        self.put('a.py', '# one\nx = 1\n')
        out = io.StringIO()
        self.assertEqual(cd.main(['--update'], root=self.root, out=out), 0)
        self.assertEqual(self.baseline(), {'a.py': 1})

    def test_the_baseline_flag_chooses_another_file(self):
        other = self.root / 'tools' / 'debt.json'
        other.parent.mkdir()
        self.put('a.py', '# one\nx = 1\n')
        out = io.StringIO()
        self.assertEqual(cd.main(['--update', '--baseline', str(other)], root=self.root, out=out), 0)
        self.assertEqual(json.loads(other.read_text()), {'a.py': 1})

    def test_an_empty_or_whitespace_only_baseline_flag_is_refused_naming_the_flag(self):
        self.put('a.py', '# one\nx = 1\n')
        for value in ('', '  '):
            for mode in ([], ['--update']):
                with self.subTest(value=value, mode=mode):
                    out = io.StringIO()
                    self.assertEqual(cd.main([*mode, '--baseline', value], root=self.root, out=out), 2)
                    self.assertIn('--baseline was given an empty path', out.getvalue())
        self.assertFalse(self.file.exists())

    def choose(self, chosen=('no-comments',), exclude=(), comment_gate_exclude=(), conventions=()):
        (self.root / 'quality-gates.json').write_text(json.dumps({
            'format_version': 1,
            'languages': ['python'],
            'exclude': list(exclude),
            'components': {'chosen': list(chosen), 'declined': []},
            'commit_time_limit_seconds': 2,
            'settings': {'no-comments': {'exclude': list(comment_gate_exclude), 'conventions': list(conventions)}},
        }))

    def keep_untracked(self, name, text):
        path = self.root / name
        path.parent.mkdir(parents=True, exist_ok=True)
