class CountingTest(unittest.TestCase):

    def test_a_hash_comment_on_its_own_line_is_debt(self):
        self.assertEqual(list(cd.debt_kinds('x = 1\n# why\ny = 2\n')), [2])

    def test_a_trailing_comment_is_debt(self):
        self.assertEqual(list(cd.debt_kinds('x = 1  # why\n')), [1])

    def test_every_line_of_a_docstring_is_debt(self):
        source = 'def f():\n    """One.\n\n    Two.\n    """\n    return 1\n'
        self.assertEqual(list(cd.debt_kinds(source)), [2, 3, 4, 5])

    def test_a_bare_string_used_as_a_comment_is_debt(self):
        source = 'def f():\n    x = 1\n    "why"\n    return x\n'
        self.assertEqual(list(cd.debt_kinds(source)), [3])

    def test_a_hash_inside_a_string_is_not_a_comment(self):
        self.assertEqual(list(cd.debt_kinds('url = "a#b"\ncolour = "#fff"\n')), [])

    def test_a_string_that_is_assigned_is_not_debt(self):
        self.assertEqual(list(cd.debt_kinds('HELP = """usage"""\n')), [])

    def test_a_shebang_and_a_coding_cookie_are_exempt(self):
        source = '#!/usr/bin/env python3\n# -*- coding: utf-8 -*-\nx = 1\n'
        self.assertEqual(list(cd.debt_kinds(source)), [])

    def test_a_shebang_after_line_one_is_debt(self):
        self.assertEqual(list(cd.debt_kinds('x = 1\n#!/bin/sh\n')), [2])

    def test_a_bare_pragma_is_exempt(self):
        source = (
            'import a  # noqa: E402\n'
            'import b  # noqa: E402, F401\n'
            'x = 1  # type: ignore[valid-type]\n'
            'if y:  # pragma: no cover\n'
            '    pass\n'
        )
        self.assertEqual(list(cd.debt_kinds(source)), [])

    def test_a_pragma_that_carries_prose_is_debt(self):
        self.assertEqual(list(cd.debt_kinds('import a  # noqa: E402  (path set above)\n')), [1])


def rust_lines(source, conventions=()):
    return list(cd.LANGUAGES['rust'].checker(source, conventions))


class RustCountingTest(unittest.TestCase):

    def test_doc_comments_count_on_every_line(self):
        source = '//! Crate.\n/// Item.\n/** Block\n    doc. */\n/*! Inner. */\nfn f() {}\n'
        self.assertEqual(rust_lines(source), [1, 2, 3, 4, 5])

    def test_a_block_comment_counts_once_per_line(self):
        source = 'fn f() -> i32 {\n    /* this whole\n       block is a comment */\n    4\n}\n'
        self.assertEqual(rust_lines(source), [2, 3])

    def test_a_nested_block_comment_counts_until_its_outer_comment_closes(self):
        self.assertEqual(rust_lines('/* a\n/* b */\nc */\nfn f() {}\n'), [1, 2, 3])

    def test_a_raw_string_holding_slashes_is_not_a_comment(self):
        source = 'let a = r#"path "a//b" and // here"#;\nlet b = br#"x "//" y"#;\nlet c = r"/* x";\nlet d = cr#"x "//" y"#;\n'
        self.assertEqual(rust_lines(source), [])

    def test_slashes_in_strings_byte_strings_and_char_literals_are_not_comments(self):
        source = ('let a = "https://example.com";\nlet b = b"//";\nlet c = format!("{}//{}", 1, 2);\n'
                  "let d = '\"'; let e = \"//\";\nlet f = b'\"'; let g = b\"//\";\n"
                  "let h = '\\''; let i = \"'//'\";\nlet j = '\\\"'; let k = \"//\";\n")
        self.assertEqual(rust_lines(source), [])

    def test_a_lifetime_is_not_the_start_of_a_char_literal(self):
        source = "struct S<'a> { t: &'a str }\nfn f<'a>(s: &'a str) -> &'a str { s } // it's why\n"
        self.assertEqual(rust_lines(source), [2])

    def test_a_trailing_comment_counts(self):
        self.assertEqual(rust_lines('let x = 1; // why\n'), [1])

    def test_a_bare_generated_marker_is_exempt_and_one_that_carries_prose_counts(self):
        self.assertEqual(rust_lines('// @generated\nfn f() {}\n'), [])
        self.assertEqual(rust_lines('// @generated by build.rs, edit it freely\nfn f() {}\n'), [1])


SAFETY = ['rust-safety']


class RustSafetyTest(unittest.TestCase):

    def test_a_safety_comment_and_its_following_lines_above_an_unsafe_block_are_allowed_only_when_switched_on(self):
        source = 'fn f() {\n    // SAFETY: the pointer is live.\n    // It came from a reference.\n    unsafe {\n    }\n}\n'
        self.assertEqual(rust_lines(source, SAFETY), [])
        self.assertEqual(rust_lines(source), [2, 3])

    def test_a_safety_comment_above_a_line_holding_an_unsafe_block_is_allowed(self):
        self.assertEqual(rust_lines('// SAFETY: from AppKit.\nlet ev = unsafe { event.as_ref() };\n', SAFETY), [])

    def test_a_safety_comment_above_an_unsafe_impl_is_allowed(self):
        self.assertEqual(rust_lines('// SAFETY: no shared state.\nunsafe impl Send for S {}\n', SAFETY), [])

    def test_a_safety_comment_above_anything_else_counts(self):
        for below in ('pub unsafe fn f() {}', 'let value = 1;', '', '// SAFETY: again', 'let s = "unsafe {";'):
            with self.subTest(below=below):
                self.assertIn(1, rust_lines(f'// SAFETY: why.\n{below}\nfn g() {{}}\n', SAFETY))

    def test_a_comment_above_the_safety_comment_still_counts(self):
        self.assertEqual(rust_lines('// note\n// SAFETY: why.\nunsafe {}\n', SAFETY), [1])

    def test_a_safety_comment_that_is_not_a_plain_line_comment_on_its_own_line_counts(self):
        for comment in ('let a = 1; // SAFETY: why.', '/// SAFETY: why.', '/* SAFETY: why. */'):
            with self.subTest(comment=comment):
                self.assertEqual(rust_lines(f'{comment}\nunsafe {{}}\n', SAFETY), [1])

    def test_the_conventions_the_gate_allows_are_exactly_those_the_conventions_page_records(self):
        allowed = {name for row in cd.LANGUAGES.values() if row.syntax for name in row.syntax.conventions}
        self.assertEqual(sorted(allowed), sorted(recorded_convention_ids()))

    def test_a_doc_or_block_comment_ends_the_lines_that_follow_a_safety_comment(self):
        for follower in ('/// more', '/* more */'):
            with self.subTest(follower=follower):
                self.assertEqual(rust_lines(f'// SAFETY: why.\n{follower}\nunsafe {{}}\n', SAFETY), [1, 2])


