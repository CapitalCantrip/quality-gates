import argparse
from pathlib import Path

from quality_gates import comment_debt, crap, languages, manifest, quality_check

COMMAND = "python -m quality_gates.languages_table"
DEFAULT_PATH = Path("docs") / "languages-by-gates.md"
GATES = {"comment-debt": comment_debt.LANGUAGES, "cc-check": quality_check.LANGUAGES, "crap": crap.LANGUAGES}
SCORES = "scores"
NOT_SCORED = "—"
NONE_INSTALLED = "none"
MATCHES = "The languages-by-gates table matches the gate tables."


def row(cells):
    return "| " + " | ".join(cells) + " |"


def installed(name, components):
    return ", ".join(c.id for c in components if name in c.languages) or NONE_INSTALLED


def language_row(language, components):
    scored = [SCORES if language.name in table else NOT_SCORED for table in GATES.values()]
    return row([language.label, *scored, installed(language.name, components)])


def render():
    components = manifest.load_components().components
    header = ["Language", *GATES, "Components installed for it"]
    lines = [
        "# Languages by gates",
        "",
        f"Generated by `{COMMAND}` from the language registry, each gate's language table and "
        "`components.json`. To change it, edit those and rerun the command.",
        "",
        row(header),
        row(["---"] * len(header)),
        *(language_row(language, components) for language in languages.REGISTERED),
    ]
    return "\n".join(lines) + "\n"


def check(path):
    path = Path(path)
    if not path.is_file():
        return [f"{path}: missing; run {COMMAND}"]
    if path.read_text(encoding="utf-8") != render():
        return [f"{path}: differs from the gate tables; run {COMMAND}"]
    return []


def build_parser():
    parser = argparse.ArgumentParser(
        prog=COMMAND,
        description="Write the table of which gates score each registered language. Run from the quality-gates repo root.",
    )
    parser.add_argument("--path", type=Path, default=DEFAULT_PATH, help=f"default: {DEFAULT_PATH}")
    parser.add_argument("--check", action="store_true", help="exit 1 if the table differs from the gate tables")
    return parser


def main(argv=None):
    args = build_parser().parse_args(argv)
    if args.check:
        problems = check(args.path)
        print("\n".join(problems) if problems else MATCHES)
        return 1 if problems else 0
    args.path.write_text(render(), encoding="utf-8")
    print(f"Wrote {args.path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
