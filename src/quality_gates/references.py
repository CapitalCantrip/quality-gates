import argparse
import os
import re
import sys
from collections import namedtuple
from pathlib import Path

from quality_gates import amendments
from quality_gates.fences import Fences

REFERENCES = "references"
DEFAULT_ADR_DIR = Path("docs") / "adr"
DEFAULT_SKILLS = Path("src") / "quality_gates" / "skills"
TAG = re.compile(r"^<!-- (/?)rule:([a-z0-9-]+) -->$")
HEADING = re.compile(r"^(#{2,6}) (.+)$")
LINK = re.compile(r"\]\(([^)]*references/[^)]*)\)")
LINK_TITLE = re.compile(r"""^(?:"[^"]*"|'[^']*')$""")
WEB_ADDRESS = re.compile(r"^[a-z][a-z0-9+.-]*:", re.IGNORECASE)
READABLE_LINK = re.compile(r"^(?:\./)?(?:\.\./)*references/([a-z0-9-]+)\.md(?:#[a-z0-9-]*)?$")
SECTION_SEPARATOR = " › "
OUTSIDE_POINTERS = [
    re.compile(r"\b(?:on|since|of|from|before|until|after) 20\d\d-\d\d-\d\d\b", re.IGNORECASE),
    re.compile(r"\baddend(?:um|a)\b", re.IGNORECASE),
    re.compile(r"(?<![\w`])#\d+"),
    re.compile(r"\((?:see )?(?:below|above)\)|\bsee (?:below|above)\b|\bthe text (?:below|above)\b"),
    re.compile(r"\b(?:see|under) Rejected\b"),
    re.compile(r"\bADR-\d{3}\b"),
    re.compile(r"\bGLOSSARY\.md\b|\bREADME\b|\bCHANGELOG\b|\bupstream\.json\b"),
    re.compile(r"(?<![\w/.-])docs/"),
    re.compile(r"\bthis (?:repo|ADR|note)\b"),
    re.compile(r"\]\(#"),
]

Rule = namedtuple("Rule", "name adr section text where")
Link = namedtuple("Link", "source text name target")
Outcome = namedtuple("Outcome", "written problems")


def adr_id(path):
    return "-".join(path.stem.split("-")[:2])


def nested_section(headings, level, title):
    return [(kept_level, kept) for kept_level, kept in headings if kept_level < level] + [(level, title)]


class AdrReader:
    def __init__(self, path):
        self.path = path
        self.lines = path.read_text(encoding="utf-8").splitlines()
        self.headings = []
        self.fences = Fences()
        self.opened = {}
        self.rules = []
        self.problems = []

    def where(self, index):
        return f"{self.path.name}:{index + 1}"

    def section(self):
        return SECTION_SEPARATOR.join(title for _, title in self.headings)

    def read(self):
        for index, line in enumerate(self.lines):
            self.read_line(index, line)
        for name, (index, _) in self.opened.items():
            self.problems.append(f"{self.where(index)}: rule:{name} has no closing tag")
        return self.rules, self.problems

    def read_line(self, index, line):
        if self.fences.inside(line):
            return
        heading = HEADING.match(line)
        if heading:
            self.headings = nested_section(self.headings, len(heading.group(1)), heading.group(2).strip())
            return
        tag = TAG.match(line.strip())
        if tag:
            (self.close if tag.group(1) else self.open)(index, tag.group(2))

    def open(self, index, name):
        if name in self.opened:
            self.problems.append(f"{self.where(index)}: rule:{name} is opened again before it is closed")
            return
        self.opened[name] = (index, self.section())

    def close(self, index, name):
        if name not in self.opened:
            self.problems.append(f"{self.where(index)}: /rule:{name} closes a tag that is not open")
            return
        start, section = self.opened.pop(name)
        body = [line for line in self.lines[start + 1:index] if not TAG.match(line.strip())]
        text = "\n".join(body).strip("\n")
        self.rules.append(Rule(name, adr_id(self.path), section, text, self.where(start)))


def outside_pointers(rule):
    found = []
    for pointer in OUTSIDE_POINTERS:
        found += [f"{rule.where}: rule:{rule.name} points outside its reference file: {match.group(0)}"
                  for match in pointer.finditer(rule.text)]
    return found


def read_rules(adr_dir):
    rules, problems = {}, []
    for path in sorted(Path(adr_dir).glob("ADR-*.md")):
        found, faults = AdrReader(path).read()
        problems += faults + amendments.problems(path)
        for rule in found:
            problems += outside_pointers(rule)
        for rule in found:
            if rule.name in rules:
                problems.append(f"rule:{rule.name} is tagged twice, at {rules[rule.name].where} and {rule.where}")
                continue
            rules[rule.name] = rule
    return rules, problems


def render(rule):
    title = rule.name.replace("-", " ").capitalize()
    return (
        f"# {title}\n\n"
        f"Generated by `qg-references` from {rule.adr}, section \"{rule.section}\", in the quality-gates repo. "
        f"To change this rule, edit that section and rerun `qg-references`.\n\n"
        f"{rule.text}\n"
    )


def skill_documents(skills_dir):
    for path in sorted(Path(skills_dir).rglob("*.md")):
        if REFERENCES not in path.relative_to(skills_dir).parts:
            yield path


def own_reference(skills_dir, source, name):
    skill = source.relative_to(skills_dir).parts[0]
    return normalised(Path(skills_dir) / skill / REFERENCES / f"{name}.md")


def links(skills_dir):
    found = []
    for source in skill_documents(skills_dir):
        for match in LINK.finditer(source.read_text(encoding="utf-8")):
            target = link_target(match.group(1))
            if target is not None:
                found.append(read_link(source, target))
    return found


def link_target(inside):
    parts = inside.strip().split(None, 1)
    if not parts or WEB_ADDRESS.match(parts[0]):
        return None
    if len(parts) == 2 and not LINK_TITLE.match(parts[1].strip()):
        return inside.strip()
    return parts[0]


def read_link(source, text):
    readable = READABLE_LINK.match(text)
    if not readable:
        return Link(source, text, None, None)
    return Link(source, text, readable.group(1), normalised(source.parent / text.split("#")[0]))


def normalised(path):
    return Path(os.path.normpath(path))


def link_problem(skills_dir, link, rules):
    where = link.source.relative_to(skills_dir).as_posix()
    if link.name is None:
        return f"{where}: cannot read the link {link.text}; write it as references/<name>.md"
    if link.name not in rules:
        return f"{where}: links references/{link.name}.md, but no ADR tags rule:{link.name}"
    if link.target != own_reference(skills_dir, link.source, link.name):
        return f"{where}: the link to {link.name}.md does not reach its skill's references folder"
    return None


def plan(adr_dir, skills_dir):
    skills_dir = normalised(skills_dir)
    rules, problems = read_rules(normalised(adr_dir))
    wanted = {}
    for link in links(skills_dir):
        problem = link_problem(skills_dir, link, rules)
        if problem:
            problems.append(problem)
        else:
            wanted[link.target] = rules[link.name]
    return wanted, problems


def generate(adr_dir, skills_dir):
    wanted, problems = plan(adr_dir, skills_dir)
    if problems:
        return Outcome(0, problems)
    write(normalised(skills_dir), wanted)
    return Outcome(len(wanted), [])


def write(skills_dir, wanted):
    for target, rule in wanted.items():
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(render(rule), encoding="utf-8")
    for stray in strays(skills_dir, wanted):
        stray.unlink()
        if not any(stray.parent.iterdir()):
            stray.parent.rmdir()


def strays(skills_dir, wanted):
    present = sorted(normalised(path) for path in Path(skills_dir).glob(f"*/{REFERENCES}/*.md"))
    return [path for path in present if path not in wanted]


def drift(skills_dir, target, rule):
    where = target.relative_to(skills_dir).as_posix()
    if not target.is_file():
        return f"{where}: missing; run qg-references"
    if target.read_text(encoding="utf-8") != render(rule):
        return f"{where}: differs from rule:{rule.name} in {rule.adr}"
    return None


def check(adr_dir, skills_dir):
    wanted, problems = plan(adr_dir, skills_dir)
    skills_dir = normalised(skills_dir)
    found = [drift(skills_dir, target, rule) for target, rule in wanted.items()]
    found += [f"{path.relative_to(skills_dir).as_posix()}: not generated; run qg-references"
              for path in strays(skills_dir, wanted)]
    return problems + [problem for problem in found if problem]


def build_parser():
    parser = argparse.ArgumentParser(
        prog="qg-references",
        description="Write each rule tagged <!-- rule:NAME --> in the ADRs to references/NAME.md in every skill that "
                    "links it, and remove reference files no skill links. Run from the quality-gates repo root.",
    )
    parser.add_argument("--adr-dir", type=Path, default=DEFAULT_ADR_DIR, help="default: docs/adr")
    parser.add_argument("--skills", type=Path, default=DEFAULT_SKILLS, help="default: src/quality_gates/skills")
    parser.add_argument("--check", action="store_true", help="exit 1 if any reference file differs from its ADR")
    return parser


def report(problems, success):
    for problem in problems:
        print(problem)
    if problems:
        sys.exit(1)
    print(success)
    sys.exit(0)


def main(argv=None):
    args = build_parser().parse_args(argv)
    if args.check:
        report(check(args.adr_dir, args.skills), "Every reference file matches its tagged ADR section.")
    outcome = generate(args.adr_dir, args.skills)
    report(outcome.problems, f"Wrote {outcome.written} reference file(s) to {args.skills}")


if __name__ == "__main__":
    main()
